#!/usr/bin/env python3
"""Qualify packed native serving through discovery, fixed workspace and frozen arena.

Run inside the NPU container with CANN/vendor environment already configured.
Inputs are existing token fixtures and qualified reference output, not models
generated by this script. Rust compilation never runs here.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import time


def records(path):
    return [record for line in path.read_text().splitlines() if line.startswith('{')
            for record in [json.loads(line)] if 'request' in record]


def stage(args, name, plan, prepare, reference):
    output = Path(str(args.output_prefix) + '-' + name)
    output.mkdir()  # Never overwrite earlier evidence.
    (output / 'prepared').mkdir()
    (output / 'transfers').mkdir()
    env = os.environ.copy()
    for key in ('INFERFABRIC_PREPARE_ARENA', 'INFERFABRIC_OUTPUT_DIAGNOSTICS'):
        env.pop(key, None)
    if prepare:
        env['INFERFABRIC_PREPARE_ARENA'] = '1'
    env.update(INFERFABRIC_PACKED_PREFILL='1', INFERFABRIC_INTERLEAVE_RESIDENTS='1',
               INFERFABRIC_SEQUENCE_BATCH='1', INFERFABRIC_EXPERIMENTAL_LONG_CONTEXT='1',
               INFERFABRIC_DECODE_GRAPH='1', INFERFABRIC_PAGE_BINDINGS=str(args.bindings.resolve()),
               INFERFABRIC_PREPARED_AUDIT_DIR=str((output / 'prepared').resolve()),
               INFERFABRIC_TRANSFER_AUDIT_DIR=str((output / 'transfers').resolve()))
    command = [str(args.binary.resolve()), str(plan.resolve()), str(args.checkpoint.resolve()), str(args.requests.resolve())]
    began = time.monotonic()
    with (output / 'tokens.jsonl').open('w') as stdout, (output / 'stderr.log').open('w') as stderr:
        process = subprocess.run(command, env=env, stdout=stdout, stderr=stderr, check=False)
    (output / 'process.json').write_text(json.dumps({'returncode': process.returncode,
        'elapsed_seconds': time.monotonic() - began, 'command': command, 'preparation': prepare}, indent=2) + '\n')
    if process.returncode:
        raise RuntimeError(f'{name}: native exited {process.returncode}; inspect {output / "stderr.log"}')
    actual = records(output / 'tokens.jsonl')
    observed = {(r['request'], r['step']): r['token'] for r in actual}
    if len(observed) != len(actual) or observed != reference:
        raise RuntimeError(f'{name}: missing, duplicate or differing reference output')
    ranks = len(list(plan.glob('rank-*.bin')))
    audits = [json.loads((output / 'prepared' / f'rank-{rank}.json').read_text()) for rank in range(ranks)]
    transfers = [json.loads((output / 'transfers' / f'rank-{rank}.json').read_text()) for rank in range(ranks)]
    if not ranks or any(t['activation_host_transfers'] or t['rejected'] for t in transfers):
        raise RuntimeError(f'{name}: missing ranks or forbidden transfer')
    if any(not any(g['name'].startswith('sequence_decode_') and g['replays'] > 1 for g in a['graphs']) for a in audits):
        raise RuntimeError(f'{name}: sequence decode replay not exercised')
    if name != 'discovery' and any(not a['workspace']['planned'] or a['workspace']['growth_allocations'] for a in audits):
        raise RuntimeError(f'{name}: shared workspace is not fixed')
    if name == 'frozen' and any(not a['arena']['frozen'] for a in audits):
        raise RuntimeError('frozen: arena was not bound')
    summary = {'passed': True, 'stage': name, 'exact_output_tokens': len(actual),
               'requests': len({r['request'] for r in actual}),
               'arena_bytes': [a['arena']['bytes'] for a in audits],
               'workspace_bytes': [a['workspace']['peak_requested_bytes'] for a in audits],
               'activation_host_transfers': [t['activation_host_transfers'] for t in transfers]}
    (output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary), flush=True)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('binary', 'plan', 'checkpoint', 'requests', 'bindings', 'reference-output', 'output-prefix'):
        parser.add_argument('--' + name, type=Path, required=True)
    args = parser.parse_args()
    reference_rows = records(args.reference_output)
    reference = {(r['request'], r['step']): r['token'] for r in reference_rows}
    if not reference or len(reference) != len(reference_rows):
        raise ValueError('empty or duplicate reference output')
    scripts = Path(__file__).resolve().parent
    discovery = stage(args, 'discovery', args.plan, True, reference)
    fixed_plan = Path(str(args.output_prefix) + '-fixed-plan')
    subprocess.run([sys.executable, str(scripts / 'plan-shared-workspace.py'), str(args.plan),
                    str(fixed_plan), str(discovery / 'prepared')], check=True)
    fixed = stage(args, 'fixed', fixed_plan, True, reference)
    frozen_plan = Path(str(args.output_prefix) + '-frozen-plan')
    subprocess.run([sys.executable, str(scripts / 'bind-prepared-arena.py'), str(fixed_plan),
                    str(fixed / 'prepared'), str(frozen_plan)], check=True)
    stage(args, 'frozen', frozen_plan, False, reference)


if __name__ == '__main__':
    main()
